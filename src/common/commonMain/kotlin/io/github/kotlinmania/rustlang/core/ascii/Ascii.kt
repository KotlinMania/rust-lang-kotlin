// Operations on ASCII strings and characters.
//
// Most string operations in Rust act on UTF-8 strings. However, at times it
// makes more sense to only consider the ASCII character set for a specific
// operation.
//
// The [escapeDefault] function provides an iterator over the bytes of an
// escaped version of the character given.

private class DebugStruct(
    private val out: StringBuilder,
    private val name: String,
) {
    private val fields: MutableList<String> = mutableListOf()

    public fun field(name: String, value: Any?): DebugStruct =
        apply {
            fields.add("$name: $value")
        }

    public fun finish() {
        if (fields.isEmpty()) {
            out.append(name)
        } else {
            out.append("$name { ${fields.joinToString(", ")} }")
        }
    }

    public fun finishNonExhaustive() {
        fields.add("..")
        finish()
    }
}

/**
 * An iterator over the escaped version of a byte.
 *
 * This `class` is created by the [escapeDefault] function. See its
 * documentation for more.
 */
public open class EscapeDefault internal constructor(
    valueCtorArg: EscapeIterInner<AlwaysEscaped>,
) : Iterable<UByte> {
    public var value: EscapeIterInner<AlwaysEscaped> = valueCtorArg
        internal set

    public var field0: EscapeIterInner<AlwaysEscaped>
        get() = value
        set(v) {
            value = v
        }

    override fun iterator(): Iterator<UByte> = object : AbstractIterator<UByte>() {
        override fun computeNext() {
            when (val v = this@EscapeDefault.next()) {
                null -> done()
                else -> setNext(v)
            }
        }
    }

    public open fun clone(): EscapeDefault = EscapeDefault(value)

    public open fun next(): UByte? = this.value.next()

    public open fun sizeHint(): Pair<Int, Int?> {
        val n = this.value.len()
        return Pair(n, n)
    }

    public open fun count(): Int = this.value.len()

    public open fun last(): UByte? = this.value.nextBack()

    public open fun advanceBy(n: Int): Result<Unit, NonZero<Int, NonZeroUsizeInner>> = this.value.advanceBy(n)

    public open fun nextBack(): UByte? = this.value.nextBack()

    public open fun advanceBackBy(n: Int): Result<Unit, NonZero<Int, NonZeroUsizeInner>> = this.value.advanceBackBy(n)

    public open fun len(): Int = this.value.len()

    public open fun fmt(f: StringBuilder): Result<Unit, Unit> = run { f.append((this.value).toString()); Result.Ok<Unit, Unit>(Unit) }

    public open fun fmtDebug(f: StringBuilder): Result<Unit, Unit> = run { DebugStruct(f, "EscapeDefault").finishNonExhaustive(); Result.Ok<Unit, Unit>(Unit) }

    public companion object {
        public operator fun invoke(
            value: EscapeIterInner<AlwaysEscaped>,
        ): EscapeDefault = EscapeDefault(
            valueCtorArg = value,
        )

        public fun new(c: UByte): EscapeDefault = EscapeDefault(EscapeIterInner.ascii(c))

        public fun empty(): EscapeDefault = EscapeDefault(EscapeIterInner.empty())
    }
}

/**
 * Returns an iterator that produces an escaped version of a `UByte`.
 *
 * The default is chosen with a bias toward producing literals that are
 * legal in a variety of languages, including C++11 and similar C-family
 * languages. The exact rules are:
 *
 * * Tab is escaped as `\t`.
 * * Carriage return is escaped as `\r`.
 * * Line feed is escaped as `\n`.
 * * Single quote is escaped as `\'`.
 * * Double quote is escaped as `\"`.
 * * Backslash is escaped as `\\`.
 * * Any character in the printable ASCII' range `0x20` .. `0x7e`
 *   inclusive is not escaped.
 * * Any other chars are given hex escapes of the form '\xNN'.
 * * Unicode escapes are never generated by this function.
 *
 * # Examples
 *
 * ```kotlin
 * import std.ascii
 *
 * val escaped = ascii.escapeDefault(48u.toUByte()).next()!!
 * check(48u.toUByte() == escaped)
 * var escaped1 = ascii.escapeDefault(9u.toUByte())
 * check(92u.toUByte() == escaped1.next()!!)
 * check(116u.toUByte() == escaped1.next()!!)
 * var escaped2 = ascii.escapeDefault(13u.toUByte())
 * check(92u.toUByte() == escaped2.next()!!)
 * check(114u.toUByte() == escaped2.next()!!)
 * var escaped3 = ascii.escapeDefault(10u.toUByte())
 * check(92u.toUByte() == escaped3.next()!!)
 * check(110u.toUByte() == escaped3.next()!!)
 * var escaped4 = ascii.escapeDefault(39u.toUByte())
 * check(92u.toUByte() == escaped4.next()!!)
 * check(39u.toUByte() == escaped4.next()!!)
 * var escaped5 = ascii.escapeDefault(34u.toUByte())
 * check(92u.toUByte() == escaped5.next()!!)
 * check(34u.toUByte() == escaped5.next()!!)
 * var escaped6 = ascii.escapeDefault(92u.toUByte())
 * check(92u.toUByte() == escaped6.next()!!)
 * check(92u.toUByte() == escaped6.next()!!)
 * var escaped7 = ascii.escapeDefault(157u.toUByte())
 * check(92u.toUByte() == escaped7.next()!!)
 * check(120u.toUByte() == escaped7.next()!!)
 * check(57u.toUByte() == escaped7.next()!!)
 * check(100u.toUByte() == escaped7.next()!!)
 * ```
 */
public fun escapeDefault(c: UByte): EscapeDefault = EscapeDefault.new(c)
