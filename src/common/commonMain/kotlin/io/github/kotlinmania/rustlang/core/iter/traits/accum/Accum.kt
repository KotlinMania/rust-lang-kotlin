/**
 * Takes each element in the [Iterator]: if it is an [Err], no further
 * elements are taken, and the [Err] is returned. Should no [Err]
 * occur, the sum of all elements is returned.
 *
 * # Examples
 *
 * This sums up every integer in a vector, rejecting the sum if a negative
 * element is encountered:
 *
 * ```kotlin
 * val f = { x: Int -> if (x < 0) {
 *     Result.failure("Negative element found")
 * } else {
 *     Result.success(x)
 * } }
 * val v = mutableListOf(1, 2)
 * val res: Result<Int> = ArrayDeque((ArrayDeque(v)).map(f)).sum()
 * check(res == Result.success(3))
 * val v1 = mutableListOf(1, -2)
 * val res1: Result<Int> = ArrayDeque((ArrayDeque(v1)).map(f)).sum()
 * check(res1 == Result.failure("Negative element found"))
 * ```
 */
public fun <T, U, E, I> sumResultTE(iter: I): Result<T, E> where T : Sum<U, T>, I : Iterator<Result<U, E>> = tryProcess(iter, { i -> i.sum() })

/**
 * Takes each element in the [Iterator]: if it is an [Err], no further
 * elements are taken, and the [Err] is returned. Should no [Err]
 * occur, the product of all elements is returned.
 *
 * # Examples
 *
 * This multiplies each number in a vector of strings,
 * if a string could not be parsed the operation returns `Err`:
 *
 * ```kotlin
 * val nums = mutableListOf("5", "10", "1", "2")
 * val total: Result<Int> = ArrayDeque((ArrayDeque(nums)).map({ w -> (w.toIntOrNull()?.let { Result.success(it) } ?: Result.failure(IllegalArgumentException("failed to parse Int"))) })).product()
 * check(total == Result.success(100))
 * val nums1 = mutableListOf("5", "10", "one", "2")
 * val total1: Result<Int> = ArrayDeque((ArrayDeque(nums1)).map({ w -> (w.toIntOrNull()?.let { Result.success(it) } ?: Result.failure(IllegalArgumentException("failed to parse Int"))) })).product()
 * check(total1.isErr())
 * ```
 */
public fun <T, U, E, I> productResultTE(iter: I): Result<T, E> where T : Product<U, T>, I : Iterator<Result<U, E>> = tryProcess(iter, { i -> i.product() })

/**
 * Takes each element in the [Iterator]: if it is a [None], no further
 * elements are taken, and the [None] is returned. Should no [None]
 * occur, the sum of all elements is returned.
 *
 * # Examples
 *
 * This sums up the position of the character `a` in a vector of strings,
 * if a word did not have the character `a` the operation returns `None`:
 *
 * ```kotlin
 * val words = mutableListOf("have", "a", "great", "day")
 * val total: Int? = ArrayDeque((ArrayDeque(words)).map({ w -> w.indexOf('a').takeIf { it >= 0 } })).sum()
 * check(total == 5)
 * val words1 = mutableListOf("have", "a", "good", "day")
 * val total1: Int? = ArrayDeque((ArrayDeque(words1)).map({ w -> w.indexOf('a').takeIf { it >= 0 } })).sum()
 * check(total1 == null)
 * ```
 */
public fun <T, U, I> sumOptionT(iter: I): T? where T : Sum<U, T>, I : Iterator<U?> = tryProcess(iter, { i -> i.sum() })

