// Windows SEH
//
// On Windows (currently only on MSVC), the default exception handling
// mechanism is Structured Exception Handling (SEH). This is quite different
// than Dwarf-based exception handling (e.g., what other unix platforms use) in
// terms of compiler internals, so LLVM is required to have a good deal of
// extra support for SEH.
//
// In a nutshell, what happens here is:
//
// 1. The `panic` function calls the standard Windows function
//    `_CxxThrowException` to throw a C++-like exception, triggering the
//    unwinding process.
// 2. All landing pads generated by the compiler use the personality function
//    `__CxxFrameHandler3`, a function in the CRT, and the unwinding code in
//    Windows will use this personality function to execute all cleanup code on
//    the stack.
// 3. All compiler-generated calls to `invoke` have a landing pad set as a
//    `cleanuppad` LLVM instruction, which indicates the start of the cleanup
//    routine. The personality (in step 2, defined in the CRT) is responsible
//    for running the cleanup routines.
// 4. Eventually the "catch" code in the `try` intrinsic (generated by the
//    compiler) is executed and indicates that control should come back to
//    Rust. This is done via a `catchswitch` plus a `catchpad` instruction in
//    LLVM IR terms, finally returning normal control to the program with a
//    `catchret` instruction.
//
// Some specific differences from the gcc-based exception handling are:
//
// * Rust has no custom personality function, it is instead *always*
//   `__CxxFrameHandler3`. Additionally, no extra filtering is performed, so we
//   end up catching any C++ exceptions that happen to look like the kind we're
//   throwing. Note that throwing an exception into Rust is undefined behavior
//   anyway, so this should be fine.
// * We've got some data to transmit across the unwinding boundary,
//   specifically a `Holder<dynamic Any + Send>`. Like with Dwarf exceptions
//   these two pointers are stored as a payload in the exception itself. On
//   MSVC, however, there's no need for an extra heap allocation because the
//   call stack is preserved while filter functions are being executed. This
//   means that the pointers are passed directly to `_CxxThrowException` which
//   are then recovered in the filter function to be written to the stack frame
//   of the `try` intrinsic.
//
// [win64]: https://docs.microsoft.com/en-us/cpp/build/exception-handling-x64
// [llvm]: https://llvm.org/docs/ExceptionHandling.html#background-on-windows-exceptions

// NOTE(nbdd0121): The `canary` field is part of stable ABI.
public open class Exception internal constructor(
    canaryCtorArg: ConstPtr,
    // This needs to be an Option because we catch the exception by reference
    // and its destructor is executed by the C++ runtime. When we take the Holder
    // out of the exception, we need to leave the exception in a valid state
    // for its destructor to run without double-dropping the Holder.
    // We also construct this as None for copies of the exception.
    public var data: RustAny?,
) {
    // See `gcc.rs` on why this is present. We already have a static here so just use it.
    public var canary: ConstPtr = canaryCtorArg
        internal set

    public companion object {
        public operator fun invoke(
            canary: ConstPtr,
            data: RustAny?,
        ): Exception = Exception(
            canaryCtorArg = canary,
            data = data,
        )
    }
}

// The purpose of all this is to implement the `panic` function below through a
// call to `_CxxThrowException`.
//
// This function takes two arguments. The first is a pointer to the data we're
// passing in, which in this case is our trait object. Pretty easy to find! The
// next, however, is more complicated. This is a pointer to a `_ThrowInfo`
// structure, and it generally is just intended to just describe the exception
// being thrown.
//
// Currently the definition of this type [1] is a little hairy, and the main
// oddity (and difference from the online article) is that on 32-bit the
// pointers are pointers but on 64-bit the pointers are expressed as 32-bit
// offsets from the image base. It's not currently possible to create a relative
// offset in const Rust code, so this is done using assembly with the `@IMGREL`
// relocation.
//
// The maze of type definitions also closely follows what LLVM emits for this
// sort of operation. For example, if you compile this C++ code on MSVC and emit
// the LLVM IR:
//
// #include <stdint.h>
//
// struct rustPanic (
// rustPanic(const rustPanic&);
// ~rustPanic();
//
// uint64T x[2];
// );
//
// void foo() (
// rustPanic a = (0, 1);
// throw a;
// )
//
// That's essentially what we're trying to emulate. Most of the constant values
// below were just copied from LLVM,
//
// In any case, these structures are all constructed in a similar manner, and
// it's just somewhat verbose for us.
//
// [1]: https://www.geoffchappell.com/studies/msvc/language/predefined/
public open class TypeDescriptor internal constructor(
    pVFTableCtorArg: ConstPtr,
    spareCtorArg: MutPtr,
    public var name: UByteArray,
) {
    public var pVFTable: ConstPtr = pVFTableCtorArg
        internal set

    public var spare: MutPtr = spareCtorArg
        internal set

    public companion object {
        public fun typeLayout(): TypeLayout<TypeDescriptor> =
            object : TypeLayout<TypeDescriptor> {
                override val alignBytes: Long = 8L
                override val sizeBytes: Long = 32L
                override fun readNative(addr: Long): TypeDescriptor =
                    TypeDescriptor(
                        (PrimitiveLayouts.constPtrLayout(64)).readNative(addr),
                        (PrimitiveLayouts.mutPtrLayout(64)).readNative(addr + 8L),
                        (PrimitiveArrayLayouts.uByteArray(11)).readNative(addr + 16L),
                    )
                override fun writeNative(addr: Long, value: TypeDescriptor) {
                    (PrimitiveLayouts.constPtrLayout(64)).writeNative(addr, value.pVFTable)
                    (PrimitiveLayouts.mutPtrLayout(64)).writeNative(addr + 8L, value.spare)
                    (PrimitiveArrayLayouts.uByteArray(11)).writeNative(addr + 16L, value.name)
                }
                override fun readBytes(buf: ByteArray, offset: Int): TypeDescriptor =
                    TypeDescriptor(
                        (PrimitiveLayouts.constPtrLayout(64)).readBytes(buf, offset),
                        (PrimitiveLayouts.mutPtrLayout(64)).readBytes(buf, offset + 8),
                        (PrimitiveArrayLayouts.uByteArray(11)).readBytes(buf, offset + 16),
                    )
                override fun writeBytes(buf: ByteArray, offset: Int, value: TypeDescriptor) {
                    (PrimitiveLayouts.constPtrLayout(64)).writeBytes(buf, offset, value.pVFTable)
                    (PrimitiveLayouts.mutPtrLayout(64)).writeBytes(buf, offset + 8, value.spare)
                    (PrimitiveArrayLayouts.uByteArray(11)).writeBytes(buf, offset + 16, value.name)
                }
            }

        public operator fun invoke(
            pVFTable: ConstPtr,
            spare: MutPtr,
            name: UByteArray,
        ): TypeDescriptor = TypeDescriptor(
            pVFTableCtorArg = pVFTable,
            spareCtorArg = spare,
            name = name,
        )
    }
}

// Note that we intentionally ignore name mangling rules here: we don't want C++
// to be able to catch Rust panics by simply declaring a `class rustPanic`.
//
// When modifying, make sure that the type name string exactly matches
// the one used in `compiler / rustcCodegenLlvm / src / intrinsic.rs`.
public val TYPE_NAME: UByteArray = "rust_panic\u0000".encodeToByteArray().toUByteArray()

// The leading `\x01` byte here is actually a magical signal to LLVM to
// *not* apply any other mangling like prefixing with a `_` character.
//
// This symbol is the vtable used by C++'s `std.typeInfo`. Objects of type
// `std.typeInfo`, type descriptors, have a pointer to this table. Type
// descriptors are referenced by the C++ EH structures defined above and
// that we construct below.
public expect val TYPE_INFO_VTABLE: UByte

// This type descriptor is only used when throwing an exception. The catch part
// is handled by the try intrinsic, which generates its own TypeDescriptor.
//
// This is fine since the MSVC runtime uses string comparison on the type name
// to match TypeDescriptors rather than pointer equality.
public var TYPE_DESCRIPTOR: TypeDescriptor = TypeDescriptor(pVFTable = addrOf(TYPE_INFO_VTABLE), spare = MutPtr(0L), name = TYPE_NAME)

public fun exceptionCleanup(e: MutPtr) {
    run {
        val matchVal = (UnresolvedTypeLayout<Exception>()).readNative((e).rawAddress)
        if (matchVal.data != null) {
            val b = matchVal.data
            (b).let { }
            rustDropPanic()
        }
    }
}

public fun exceptionCopy(dest: MutPtr, src: MutPtr): MutPtr =
    run {
        throwException(null)
    }

public fun panic(data: PanicPayload): UInt = throwException(data.takeBox())

public fun throwException(data: RustAny?): Nothing {
    fun cxxThrowException(pExceptionObject: MutPtr, pThrowInfo: ConstPtr): Nothing = run { val ptr = kmAllocZeroed(maxOf(1L, (UnresolvedTypeLayout<Nothing>()).sizeBytes), maxOf(1L, (UnresolvedTypeLayout<Nothing>()).alignBytes)); val res = (UnresolvedTypeLayout<Nothing>()).readNative(ptr); kmDealloc(ptr, maxOf(1L, (UnresolvedTypeLayout<Nothing>()).sizeBytes), maxOf(1L, (UnresolvedTypeLayout<Nothing>()).alignBytes)); res }
    // _CxxThrowException executes entirely on this stack frame, so there's no
    // need to otherwise transfer `data` to the heap. We just pass a stack
    // pointer to this function.
    //
    // The ManuallyDrop is needed here since we don't want Exception to be
    // dropped when unwinding. Instead it will be dropped by exceptionCleanup
    // which is invoked by the C++ runtime.
    val localStorageL207C4 = AddressableLocal(Exception(canary = addrOf(TYPE_DESCRIPTOR), data = data), UnresolvedTypeLayout<Any?>())
    val throwInfo: ConstPtr
    return run {
        Unit
        cxxThrowException((localStorageL207C4.asMutPtr()), throwInfo)
    }
}

public fun cleanup(payload: MutPtr): RustAny {
    // A null payload here means that we got here from the catch (...) of
    // __rust_try. This happens when a non-Rust foreign exception is caught.
    if (((payload).rawAddress == 0L)) {
        rustForeignException()
    }
    val exception = MutPtr(payload.rawAddress, payload.rawMeta)
    return run {
        val canary = (PrimitiveLayouts.constPtrLayout(64L)).readNative(((addrOf((UnresolvedTypeLayout<Exception>()).readNative((exception).rawAddress).canary))).rawAddress)
        if (!eq(canary, addrOf(TYPE_DESCRIPTOR))) {
            // A foreign Rust exception.
            rustForeignException()
        }
        (UnresolvedTypeLayout<Exception>()).readNative((exception).rawAddress).data.take()!!
    }
}
