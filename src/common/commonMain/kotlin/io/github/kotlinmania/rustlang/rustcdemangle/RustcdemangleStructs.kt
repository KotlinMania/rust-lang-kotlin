package io.github.kotlinmania.rustlang.rustcdemangle

import io.github.kotlinmania.rustlang.core.fmt.Error
import io.github.kotlinmania.rustlang.core.mem.PrimitiveLayouts
import io.github.kotlinmania.rustlang.core.mem.TypeLayout
import io.github.kotlinmania.rustlang.core.result.Result
import io.github.kotlinmania.rustlang.core.result.andThen

/**
 * Representation of a demangled symbol name.
 */
public open class Demangle(
    public var style: DemangleStyle?,
    public var original: String,
    public var suffix: String,
) {
    /**
     * Returns the underlying string that's being demangled.
     */
    public open fun asStr(): String = this.original

    public open fun fmt(f: StringBuilder) {
        when (val matchVal = this.style) {
            null -> f.append(this.original)
            else -> {
                val d = matchVal
                val alternate = f.alternate()
                var sizeLimitedFmt = SizeLimitedFmtAdapter(remaining = Result.Ok(MAX_SIZE), inner = f)
                val fmtResult =
                    if (alternate) {
                        sizeLimitedFmt.append("$d")
                    } else {
                        sizeLimitedFmt.append("$d")
                    }
                val sizeLimitResult = sizeLimitedFmt.remaining.map({ Unit })
                // Translate a `fmt.Error` generated by `SizeLimitedFmtAdapter`
                // into an error message, instead of propagating it upwards
                // (which could cause panicking from inside e.g. `std.io.print`).
                run {
                    val matchVal1 = Pair(fmtResult, sizeLimitResult)
                    when {
                        matchVal1.first is Result.Err<*> && matchVal1.second is Result.Err<*> && (matchVal1.second as Result.Err<*>).error is SizeLimitExhausted -> {
                            val SizeLimitExhausted = (matchVal1.second as Result.Err<*>).error
                            f.append("{size limit reached}")
                        }
                        else -> {
                            fmtResult
                            sizeLimitResult.expect("`fmt::Error` from `SizeLimitedFmtAdapter` was discarded")
                        }
                    }
                }
            }
        }
        f.append(this.suffix)
    }

    public open fun fmtDebug(f: StringBuilder) {
        f.append((this).toString())
    }
}

/**
 * Error returned from the `tryDemangle` function below when demangling fails.
 */
public open class TryDemangleError(
    public var priv: Unit,
) {
    public open fun clone(): TryDemangleError = TryDemangleError(priv)

    public companion object {
        public fun typeLayout(): TypeLayout<TryDemangleError> =
            object : TypeLayout<TryDemangleError> {
                override val alignBytes: Long = 1L
                override val sizeBytes: Long = 0L
                override fun readNative(addr: Long): TryDemangleError =
                    TryDemangleError(
                        (PrimitiveLayouts.UNIT).readNative(addr),
                    )
                override fun writeNative(addr: Long, value: TryDemangleError) {
                    (PrimitiveLayouts.UNIT).writeNative(addr, value.priv)
                }
                override fun readBytes(buf: ByteArray, offset: Int): TryDemangleError =
                    TryDemangleError(
                        (PrimitiveLayouts.UNIT).readBytes(buf, offset),
                    )
                override fun writeBytes(buf: ByteArray, offset: Int, value: TryDemangleError) {
                    (PrimitiveLayouts.UNIT).writeBytes(buf, offset, value.priv)
                }
            }
    }
}

public open class SizeLimitExhausted {
    public open fun clone(): SizeLimitExhausted = SizeLimitExhausted()

    public companion object {
        public fun typeLayout(): TypeLayout<SizeLimitExhausted> =
            object : TypeLayout<SizeLimitExhausted> {
                override val alignBytes: Long = 1L
                override val sizeBytes: Long = 0L
                override fun readNative(addr: Long): SizeLimitExhausted =
                    SizeLimitExhausted()
                override fun writeNative(addr: Long, value: SizeLimitExhausted) {
                }
                override fun readBytes(buf: ByteArray, offset: Int): SizeLimitExhausted =
                    SizeLimitExhausted()
                override fun writeBytes(buf: ByteArray, offset: Int, value: SizeLimitExhausted) {
                }
            }
    }
}

public open class SizeLimitedFmtAdapter<F> internal constructor(
    remainingCtorArg: Result<Int, SizeLimitExhausted>,
    public var inner: F,
) : Appendable {
    public var remaining: Result<Int, SizeLimitExhausted> = remainingCtorArg
        internal set

    public open fun writeStr(s: String) {
        this.remaining = this.remaining.andThen({ r -> (r.checkedSub(s.length)?.let { Result.Ok(it) } ?: Result.Err(SizeLimitExhausted())) })
        run {
            val matchVal = this.remaining
            when {
                matchVal is Result.Ok<*> -> this.inner.append(s)
                else -> {
                    val SizeLimitExhausted = (matchVal as Result.Err<*>).error
                    Result.Err(Error)
                }
            }
        }
    }

    public companion object {
        public operator fun <F> invoke(
            remaining: Result<Int, SizeLimitExhausted>,
            inner: F,
        ): SizeLimitedFmtAdapter<F> = SizeLimitedFmtAdapter<F>(
            remainingCtorArg = remaining,
            inner = inner,
        )
    }
}
